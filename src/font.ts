export const GLYPH_W = 5,
  GLYPH_H = 7;

/** The 7 rows (5 bits each, MSB = left) for a character; unknown characters are blank. */
export function glyph(ch: string): number[] {
  return GLYPHS[ch.toUpperCase()] ?? GLYPHS[" "];
}

/** Width in pixels of `text` at `scale`, with `gap` font pixels between characters. */
export function textWidth(text: string, scale: number, gap = 1): number {
  return text.length ? (text.length * (GLYPH_W + gap) - gap) * scale : 0;
}

/** Draws `text` (uppercased) into an RGBA buffer of width `w`. Unknown characters draw as blanks. */
export function drawText(
  rgba: Uint8Array,
  w: number,
  text: string,
  x: number,
  y: number,
  scale: number,
  color: number[],
  gap = 1,
) {
  const h = rgba.length / 4 / w;
  for (const ch of text.toUpperCase()) {
    const rows = GLYPHS[ch] ?? GLYPHS[" "];
    for (let r = 0; r < GLYPH_H; r++) {
      for (let c = 0; c < GLYPH_W; c++) {
        if (!(rows[r] & (0x10 >> c))) continue;
        for (let dy = 0; dy < scale; dy++) {
          for (let dx = 0; dx < scale; dx++) {
            const px = x + c * scale + dx,
              py = y + r * scale + dy;
            if (px >= 0 && px < w && py >= 0 && py < h)
              rgba.set([color[0], color[1], color[2], 255], (py * w + px) * 4);
          }
        }
      }
    }
    x += (GLYPH_W + gap) * scale;
  }
}
